    if ((Get-Sha $path) -ne $row.Sha256) { throw ('carrier_sha_mismatch:' + $row.Rel) }
  }
  Write-Host ('[PASS] exact accepted R13 R2 carrier guards: ' + $Carrier.Count)
}

function Write-Atomic([string]$Path,[byte[]]$Bytes) {
  $dir = Split-Path -Parent $Path
  if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
  $tmp = $Path + '.ql7-r14-r3-' + [Guid]::NewGuid().ToString('N')
  [IO.File]::WriteAllBytes($tmp,$Bytes)
  if (Test-Path -LiteralPath $Path) { Remove-Item -LiteralPath $Path -Force }
  Move-Item -LiteralPath $tmp -Destination $Path -Force
}

function Install-State([ValidateSet('PRE','POST')][string]$State) {
  foreach ($row in $Owned) {
    $path = Get-Abs $row.Rel
    if ($State -eq 'PRE') {
      $expectedExists = [bool]$row.PreExists
      $payload = $row.PrePayload
    }
    else {
      $expectedExists = [bool]$row.PostExists
      $payload = $row.PostPayload
    }

    if (-not $expectedExists) {
      if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Force }
      continue
    }

    Write-Atomic $path (Decode-Payload $payload)
  }

  if (-not (Test-State $State)) { throw ('owned_state_write_verify_failed:' + $State) }
}

function Invoke-Step([string]$Name,[scriptblock]$Command) {
