  Write-Host ''
  Write-Host ('[QL7] ' + $Name)
  $previous = $ErrorActionPreference
  $code = $null

  try {
    $ErrorActionPreference = 'Continue'
    $global:LASTEXITCODE = 0
    & $Command 2>&1 | Tee-Object -FilePath $log
    $code = $LASTEXITCODE
  }
  finally {
    $ErrorActionPreference = $previous
  }

  if ($null -eq $code) { $code = 0 }
  [void]$Steps.Add([pscustomobject]@{name=$Name;exitCode=[int]$code;log=$log})
  if ([int]$code -ne 0) { throw ('native_step_failed:' + $Name + ':exit=' + $code) }
  Write-Host ('[PASS] ' + $Name + ' exitCode=0')
}

