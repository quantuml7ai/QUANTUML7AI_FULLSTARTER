function Get-Abs([string]$Rel) {
  return Join-Path $Root ($Rel -replace '/', '\')
}

function Get-Sha([string]$Path) {
  return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToUpperInvariant()
}

function Decode-Payload([string]$Payload) {
  $compact = ($Payload -replace '\s', '')
  if ([string]::IsNullOrWhiteSpace($compact)) {
    return [byte[]]@()
  }

  $compressed = [Convert]::FromBase64String($compact)
  $input = New-Object IO.MemoryStream(,$compressed)
  $gzip = New-Object IO.Compression.GZipStream($input,[IO.Compression.CompressionMode]::Decompress)
  $output = New-Object IO.MemoryStream

  try {
    $gzip.CopyTo($output)
    return $output.ToArray()
  }
  finally {
    $gzip.Dispose()
    $input.Dispose()
    $output.Dispose()
  }
}

function Test-State([ValidateSet('PRE','POST')][string]$State) {
  foreach ($row in $Owned) {
    $path = Get-Abs $row.Rel
    $exists = Test-Path -LiteralPath $path -PathType Leaf

    if ($State -eq 'PRE') {
      $expectedExists = [bool]$row.PreExists
      $expectedSize = $row.PreSize
      $expectedSha = $row.PreSha256
    }
    else {
      $expectedExists = [bool]$row.PostExists
      $expectedSize = $row.PostSize
      $expectedSha = $row.PostSha256
    }

    if ($exists -ne $expectedExists) { return $false }
    if (-not $expectedExists) { continue }
    if ([int64](Get-Item -LiteralPath $path).Length -ne [int64]$expectedSize) { return $false }
    if ((Get-Sha $path) -ne $expectedSha) { return $false }
  }

  return $true
}

function Assert-Carrier {
  foreach ($row in $Carrier) {
    $path = Get-Abs $row.Rel
