function hasAny(text,terms=[]){const value=fold(text);return terms.some((term)=>value.includes(fold(term)))}
function hasCounter(text,terms=[]){const value=fold(text),tokens=new Set(value.match(/[\p{L}\p{N}_'-]+/gu)||[]);return terms.some((term)=>{const v=fold(term);if(!v)return false;if(/[\u3040-\u30ff\u3400-\u9fff\uac00-\ud7af]/u.test(v)||v.includes(' '))return value.includes(v);return tokens.has(v)})}
